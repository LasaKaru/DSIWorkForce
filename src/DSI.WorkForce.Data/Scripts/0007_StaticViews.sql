-- Long ("one row per value") view: handy for ad-hoc SQL, Power BI and auditing.
CREATE OR ALTER VIEW rpt.vw_WorksheetValues
AS
SELECT
    w.WorksheetId, w.TemplateCode, w.WorkDate, w.Shift, w.ResourceNo, w.EpfNo, w.ItemCode, w.Status,
    f.FieldKey, f.Label, f.GroupName, f.DataType, v.RowIndex,
    v.RawText, v.ValueText, v.ValueNumber, v.ValueDate, v.ValueBool,
    v.Confidence, v.Source, v.IsCorrected,
    sf.FileName, w.PageNo, w.CreatedAt
FROM dsi.Worksheet w
JOIN dsi.WorksheetValue v ON v.WorksheetId = w.WorksheetId
JOIN dsi.FieldDefinition f ON f.FieldId = v.FieldId
JOIN dsi.ScanFile sf ON sf.ScanFileId = w.ScanFileId;
GO
-- Machine checklist as a grid: one row per sheet, one column per check item is generated by the report
-- engine; this view gives the simple "which checks failed" list.
CREATE OR ALTER VIEW rpt.vw_ChecklistExceptions
AS
SELECT w.WorksheetId, w.WorkDate, w.Shift, w.ResourceNo, w.EpfNo, f.FieldKey, f.Label
FROM dsi.Worksheet w
JOIN dsi.WorksheetValue v ON v.WorksheetId = w.WorksheetId
JOIN dsi.FieldDefinition f ON f.FieldId = v.FieldId
WHERE f.GroupName = N'Machine Checklist' AND v.ValueBool = 0 AND w.Status <> N'Rejected';
GO
CREATE OR ALTER VIEW rpt.vw_QueueStatus
AS
SELECT Status, COUNT(*) AS Files, SUM(ISNULL(PageCount, 0)) AS Pages,
       MIN(ReceivedAt) AS OldestReceivedUtc, MAX(ReceivedAt) AS NewestReceivedUtc
FROM dsi.ScanFile
GROUP BY Status;
GO
